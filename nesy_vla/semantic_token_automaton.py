"""Generated state-machine programs grounded in discrete visual/text tokens.

Descriptions are generated by a separate frozen VLM. Only its emitted integer
token IDs cross this boundary. No VLM hidden states or image features enter.
"""
from dataclasses import dataclass
import torch
from torch import nn
from .probabilistic_automaton import ProbabilisticTokenAutomaton


@dataclass(frozen=True)
class SemanticTokens:
    visual: torch.Tensor
    text: torch.Tensor
    mask: torch.Tensor

    @property
    def shape(self):return self.visual.shape
    @property
    def ndim(self):return self.visual.ndim
    @property
    def device(self):return self.visual.device
    def __len__(self):return len(self.visual)
    def __getitem__(self,index):return SemanticTokens(self.visual[index],self.text[index],self.mask[index])


class SemanticTokenAutomaton(ProbabilisticTokenAutomaton):
    def __init__(self,word_table,**kwargs):
        super().__init__(**kwargs)
        # Frozen pretrained text-token lookup. It is referenced by hash in the
        # checkpoint manifest rather than duplicated into every checkpoint.
        self.register_buffer('word_table',word_table.detach().clone(),persistent=False)
        self.text_project=nn.Linear(word_table.shape[1],128)
        self.text_reader=nn.GRU(128,128,batch_first=True)
        self.text_to_tokens=nn.Linear(128,self.patches*8)
        nn.init.zeros_(self.text_to_tokens.weight);nn.init.zeros_(self.text_to_tokens.bias)

    def initialize_common(self,state):
        target=self.state_dict()
        assert set(state)=={k for k in target if not k.startswith(('text_project.','text_reader.','text_to_tokens.'))}
        target.update(state);self.load_state_dict(target)

    def validate_codes(self,codes):
        if not isinstance(codes,SemanticTokens):
            raise TypeError('Expected discrete patch IDs and emitted text-token IDs')
        super().validate_codes(codes.visual)
        if codes.text.dtype!=torch.long or codes.mask.dtype!=torch.bool:
            raise TypeError('Descriptions must be integer token IDs with a Boolean mask')
        if codes.text.shape!=codes.mask.shape or codes.text.shape[:-1]!=codes.visual.shape[:-1]:
            raise ValueError('Text/visual token batch dimensions do not agree')
        if not 1<=codes.text.shape[-1]<=128 or ((codes.text<0)|(codes.text>=len(self.word_table))).any():
            raise ValueError('Unknown text token or invalid description length')

    def embed(self,codes):
        self.validate_codes(codes)
        hard=self.tokens(codes.visual+self.offsets).flatten(-2)
        length=codes.text.shape[-1]
        words=self.word_table[codes.text].float().reshape(-1,length,self.word_table.shape[-1])
        mask=codes.mask.reshape(-1,length)
        encoded=torch.tanh(self.text_project(words));output,_=self.text_reader(encoded)
        summary=(output*mask[...,None]).sum(1)/mask.sum(1,keepdim=True).clamp_min(1)
        delta=self.text_to_tokens(summary)*mask.any(-1,keepdim=True)
        return hard+delta.reshape(*hard.shape)
