def stats(y,p):
    y=np.asarray(y,bool);p=np.asarray(p,float);q=p.clip(1e-7,1-1e-7)
    return dict(count=len(y),positive=int(y.sum()),empirical_frequency=float(y.mean()),predicted_frequency=float(p.mean()),
        positive_mean=float(p[y].mean()),negative_mean=float(p[~y].mean()),
        balanced_nll=float(-.5*(np.log(q[y]).mean()+np.log1p(-q[~y]).mean())),
        brier=float(((p-y)**2).mean()),recall_at_half=float((p[y]>=.5).mean()),fpr_at_half=float((p[~y]>=.5).mean()),
        impossible_positive=int(((p==0)&y).sum()))

@torch.inference_mode()
def main():
    assert os.environ.get('CUDA_VISIBLE_DEVICES')==''
    torch.set_num_threads(2);os.nice(10);start=time.time()
    src=ROOT/'goal_discrimination_v64';commit=json.loads((src/'source.COMMITTED.json').read_text())
    assert sha(src/'source.pt')==commit['sha256']
    saved=torch.load(src/'source.pt',map_location='cpu',weights_only=False)
    model=FactoredWorld(Config(**dict(saved['model_config'],linear_visual_evidence=True))).eval().requires_grad_(False)
    missing,unexpected=model.load_state_dict(saved['model'],strict=False)
    assert not unexpected and set(missing)=={'linear_visual_evidence.weight','evidence_mean','evidence_scale'}
    install(model);data=JointData(model,saved['manifest']['transition_holdout_episodes'],torch.device('cpu'));del saved
    results={}
    for part in ('fit','holdout'):
        values={name:[] for name in ('label1','label2','one_o','one_joint','two_o','two_joint','actual_one_goal_o','actual_two_goal_o')}
        # Deterministic all holdout and every third fitting pair, no new sampling.
        ids=data.parts[part]['pairs'][::3 if part=='fit' else 1]
        for index in ids.split(32):
            rows=data.pairs[index];programs,t,f0,f1,f2,a1,a2,valid,_=rows.unbind(-1);b=len(rows);ctx=data.context[programs]
            unique,back=torch.unique(programs,return_inverse=True);hist=data.history[unique]
            h,_=data.logits(model,hist,unique);ml,_,_=model.memory_sequence(hard(h),data.previous[unique],data.z[hist]);m0=hard(ml)[back,t]
            l0,_=data.logits(model,f0,programs);l1,_=data.logits(model,f1,programs);l2,_=data.logits(model,f2,programs)
            gm,go=model.goal_logits(ctx,data.task[programs]);gm=gm.argmax(-1);go=go.argmax(-1)
            lm1,lp1=model.transition(ctx,m0,hard(l0),a1);m1=hard(lm1)
            stop_m,_=model.transition(ctx,m1,F.one_hot(go,64).float(),torch.zeros_like(a1))
            mask1=torch.where(a1==0,lm1.argmax(-1)==gm,stop_m.argmax(-1)==gm)
            p1=lp1.exp().gather(1,go[:,None]).squeeze(1)
            eye=torch.eye(64)[None].expand(b,-1,-1)
            lm2,lp2=model.transition(ctx,m1[:,None].expand(-1,64,-1),eye,a2[:,None].expand(-1,64))
            stop2,_=model.transition(ctx,hard(lm2),F.one_hot(go,64).float()[:,None].expand(-1,64,-1),torch.zeros(b,64,dtype=torch.long))
            mask2=torch.where(a2[:,None]==0,lm2.argmax(-1)==gm[:,None],stop2.argmax(-1)==gm[:,None])
            p2_terms=lp1.exp()*lp2.exp().gather(-1,go[:,None,None].expand(-1,64,1)).squeeze(-1)
            use=valid.bool()
            for key,val in dict(label1=data.y[f1],label2=data.y[f2][use],one_o=p1,one_joint=p1*mask1,
                two_o=p2_terms.sum(-1)[use],two_joint=(p2_terms*mask2).sum(-1)[use],
                actual_one_goal_o=l1.softmax(-1).gather(1,go[:,None]).squeeze(1),
                actual_two_goal_o=l2.softmax(-1).gather(1,go[:,None]).squeeze(1)[use]).items():values[key].extend(val.tolist())
        results[part]={key:stats(values['label2' if key.startswith('two') or key=='actual_two_goal_o' else 'label1'],values[key])
            for key in values if not key.startswith('label')}
    result=dict(time=time.time(),seconds=time.time()-start,source=commit,training_only=True,
        normal_near_medium_only=True,dev_or_final_data_used=False,new_rollouts=0,optimizer_updates=0,device='CPU',
        hypothesis='Are table-derived probabilities of reaching the learned goal aligned with actual measured success after one/two recorded actions?',
        results=results,limitations='Binary outcome labels are used only for diagnosis. Goal IDs are generated by the existing network, not manually assigned.')
    path=ROOT/'run_normal_near_medium_v67/measured_goal_probability_audit.json';path.write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2),flush=True)
if __name__=='__main__':main()
